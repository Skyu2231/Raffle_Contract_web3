#!/usr/bin/env bash
# Deploy the raffle to a local Anvil node with the mock VRF coordinator.
#
# `forge script` cannot be used here: the mock derives subscription ids from
# `blockhash(block.number - 1)`, so the id returned during simulation is not the
# id created on-chain. This script creates the subscription with `cast` first,
# reads the real id from its event, then deploys the Raffle with that id.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

RPC_URL="${RPC_URL:-http://127.0.0.1:8545}"
PRIVATE_KEY="${PRIVATE_KEY:-0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80}"

GAS_LANE=0x474e34a077df58807dbe9c96d3c009b23b3c6d0cce433e59bbf5b34f823bc56c
INTERVAL=30
ENTRANCE_FEE=10000000000000000 # 0.01 ETH
CALLBACK_GAS_LIMIT=500000
# The mock charges VRF fees in LINK at 1 LINK = 0.004 ETH, so a draw needs far
# more than the 3 LINK used on a real network.
LINK_FUNDING=100000000000000000000 # 100 LINK

json_field() {
  node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const v=process.argv[1].split(".").reduce((a,k)=>a?.[k],JSON.parse(s));process.stdout.write(String(v))})' "$1"
}

last_log_topic() {
  node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const a=JSON.parse(s);if(!a.length)process.exit(1);process.stdout.write(a[a.length-1].topics[1])})'
}

if ! cast chain-id --rpc-url "$RPC_URL" >/dev/null 2>&1; then
  echo "No node at $RPC_URL. Start one with 'make anvil' first." >&2
  exit 1
fi

echo "Deploying mock VRF coordinator..."
COORDINATOR=$(forge create \
  lib/chainlink-brownie-contracts/contracts/src/v0.8/vrf/mocks/VRFCoordinatorV2_5Mock.sol:VRFCoordinatorV2_5Mock \
  --rpc-url "$RPC_URL" --private-key "$PRIVATE_KEY" --broadcast --json \
  --constructor-args 250000000000000000 1000000000 4000000000000000 | json_field deployedTo)

echo "Deploying mock LINK token..."
LINK=$(forge create test/mocks/LinkToken.sol:LinkToken \
  --rpc-url "$RPC_URL" --private-key "$PRIVATE_KEY" --broadcast --json | json_field deployedTo)

echo "Creating VRF subscription..."
cast send "$COORDINATOR" "createSubscription()" \
  --rpc-url "$RPC_URL" --private-key "$PRIVATE_KEY" >/dev/null

SUB_ID=$(cast logs --address "$COORDINATOR" "SubscriptionCreated(uint256,address)" \
  --from-block 0 --json --rpc-url "$RPC_URL" | last_log_topic)
SUB_ID=$(cast to-dec "$SUB_ID")

echo "Funding subscription with 100 LINK..."
cast send "$COORDINATOR" "fundSubscription(uint256,uint256)" "$SUB_ID" "$LINK_FUNDING" \
  --rpc-url "$RPC_URL" --private-key "$PRIVATE_KEY" >/dev/null

echo "Deploying Raffle..."
RAFFLE=$(forge create src/Raffle.sol:Raffle \
  --rpc-url "$RPC_URL" --private-key "$PRIVATE_KEY" --broadcast --json \
  --constructor-args "$SUB_ID" "$GAS_LANE" "$INTERVAL" "$ENTRANCE_FEE" "$CALLBACK_GAS_LIMIT" "$COORDINATOR" \
  | json_field deployedTo)

echo "Adding Raffle as a VRF consumer..."
cast send "$COORDINATOR" "addConsumer(uint256,address)" "$SUB_ID" "$RAFFLE" \
  --rpc-url "$RPC_URL" --private-key "$PRIVATE_KEY" >/dev/null

cat > frontend/.env.local <<EOF
# Generated by \`make deploy-local\`. Delete to use frontend/.env instead.
VITE_CHAIN_ID=31337
VITE_RAFFLE_ADDRESS_31337=$RAFFLE
EOF

cat <<EOF

Raffle:        $RAFFLE
VRF mock:      $COORDINATOR
LINK token:    $LINK
Subscription:  $SUB_ID

Wrote frontend/.env.local. Start the app with \`npm run dev\` in frontend/.
MetaMask: add network "Anvil" (RPC $RPC_URL, chain id 31337) and import the
Anvil test account printed by \`make anvil\` (it holds 10,000 free ETH).

After clicking "Draw winner", the mock does not auto-fulfil. Run:
  make fulfill-local RAFFLE=$RAFFLE
EOF
